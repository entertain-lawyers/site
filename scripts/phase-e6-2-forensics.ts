import { PrismaClient } from '@prisma/client';

const prisma = new PrismaClient();

async function main() {
    console.log("=== Phase E.6.2 Forensics ===");
    const dbUrl = process.env.DATABASE_URL || "";
    if (dbUrl.includes("ep-delicate-silence-b36jbzw5")) {
        console.log("Target: Production");
    } else {
        console.log("Target: Other");
    }

    // 1. Semesters
    const semesters = await prisma.semester.findMany();
    console.log(`\nSemesters Count: ${semesters.length}`);
    for (const sem of semesters) {
        console.log(` - [${sem.id}] ${sem.name} (Slug: ${sem.slug})`);
    }

    // 2. Subjects
    const subjects = await prisma.subject.findMany({
        include: {
            _count: {
                select: { resources: true, units: true }
            }
        }
    });
    console.log(`\nSubjects Count: ${subjects.length}`);

    const candidateSubjects = [];
    const validSubjects = [];

    for (const sub of subjects) {
        // E.3 generated subjects have slugs combining semester name + subject name
        // e.g. '1stsemester-jurisprudence'
        // They were specifically created with a slug that contains the word 'semester'
        if (sub.slug && sub.slug.includes('semester')) {
            candidateSubjects.push(sub);
        } else {
            validSubjects.push(sub);
        }
    }

    console.log(`\nCandidates (Generated by E.3): ${candidateSubjects.length}`);
    console.log(`Valid/Canonical Subjects: ${validSubjects.length}`);

    // Print summary of candidates
    let safeToDelete = 0;
    let requiresReview = 0;

    for (const sub of candidateSubjects) {
        const hasDependencies = sub._count.resources > 0 || sub._count.units > 0;
        console.log(` - Candidate: ${sub.name} [ID: ${sub.id}] [Slug: ${sub.slug}] | Resources: ${sub._count.resources}, Units: ${sub._count.units}`);
        if (hasDependencies) {
            requiresReview++;
        } else {
            safeToDelete++;
        }
    }

    console.log(`\nAnalysis Summary:`);
    console.log(`Safe to delete (0 dependencies): ${safeToDelete}`);
    console.log(`Requires review (>0 dependencies): ${requiresReview}`);
}

main()
    .catch(console.error)
    .finally(() => prisma.$disconnect());
